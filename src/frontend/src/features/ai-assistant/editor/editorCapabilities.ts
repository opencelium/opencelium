import { WORKFLOW_GUIDES, type WorkflowGuideId } from '@features/onboarding/guides/model/workflowGuides'

/**
 * `guide` shows where something is; `edit` changes the workflow through an AI reading of the request; `assist`
 * presses one of the editor's own buttons (run, debug, undo, save …).
 */
export type EditorCapabilityKind = 'guide' | 'edit' | 'assist'

type CapabilityEntry = {
    kind: EditorCapabilityKind
    /** `common` key: the gateway matches requests against it in English and German, the palette shows it. */
    descriptionKey: string
    /** It changes something, so a question about how to do it never runs it. */
    isAction: boolean
    /** A guide standing for this action when the request asks to be shown nothing. */
    teaches?: string
    /** The guide that takes over when the request names a method ("test getCustomers" tries one method). */
    withMethod?: string
}

const guide = (id: WorkflowGuideId, teaches?: string) =>
    ({ kind: 'guide', descriptionKey: WORKFLOW_GUIDES[id].descriptionKey, isAction: false, ...(teaches ? { teaches } : {}) }) as const

const edit = (key: string) => ({ kind: 'edit', descriptionKey: `commandPalette.descriptions.${key}`, isAction: true }) as const

const assist = (key: string, isAction: boolean, withMethod?: string) =>
    ({ kind: 'assist', descriptionKey: `commandPalette.descriptions.${key}`, isAction, ...(withMethod ? { withMethod } : {}) }) as const

/**
 * Everything a request in the workflow editor can turn into, in the order the gateway is offered them. This is the
 * one list: the routing options, the dispatch in `askWorkflowEditor`, and the gateway's eval fixture
 * (`src/ai-gateway/test/fixtures/guideCatalog.json`, regenerated by `npm run ai:catalog`) all come from it.
 */
export const EDITOR_CAPABILITIES = {
    'method-url': guide('method-url'),
    'method-headers': guide('method-headers', 'open-headers'),
    'method-body': guide('method-body', 'open-body'),
    'method-try': guide('method-try'),
    'method-transformation': guide('method-transformation', 'apply-transformation'),
    'add-method': edit('workflowAddMethod'),
    'suggest-mapping': edit('workflowSuggestMapping'),
    'apply-transformation': edit('workflowApplyTransformation'),
    'open-body': edit('workflowOpenBody'),
    'open-headers': edit('workflowOpenHeaders'),
    'add-operator': edit('workflowAddOperator'),
    'test-workflow': assist('workflowTestRun', true, 'method-try'),
    'stop-test': assist('workflowStopTest', true),
    // Not actions: "why did it fail?" and "how do I fix it?" are questions these answer, not ones to refuse.
    'explain-failure': assist('workflowExplainFailure', false),
    'fix-failure': assist('workflowFixFailure', false),
    'apply-fix': assist('workflowApplyFix', true),
    'explain-workflow': assist('workflowExplain', false),
    'show-logs': assist('workflowShowLogs', false),
    'show-problems': assist('workflowShowProblems', false),
    'undo': assist('workflowUndo', true),
    'redo': assist('workflowRedo', true),
    'save-workflow': assist('workflowSave', true),
    'delete-step': assist('workflowDeleteStep', true),
    'generate-workflow': assist('workflowGenerate', true),
    // Not an action: "how does the editor work?" is a fair reason to start it.
    'start-tutorial': assist('workflowStartTutorial', false),
} as const satisfies Record<string, CapabilityEntry>

export type EditorCapabilityId = keyof typeof EDITOR_CAPABILITIES

export type EditorCapabilityIdOf<K extends EditorCapabilityKind> = {
    [Id in EditorCapabilityId]: (typeof EDITOR_CAPABILITIES)[Id]['kind'] extends K ? Id : never
}[EditorCapabilityId]

export const EDITOR_CAPABILITY_IDS = Object.keys(EDITOR_CAPABILITIES) as EditorCapabilityId[]

export const isEditorCapabilityId = (id: string): id is EditorCapabilityId => Object.hasOwn(EDITOR_CAPABILITIES, id)

export const isCapabilityOfKind = <K extends EditorCapabilityKind>(id: EditorCapabilityId, kind: K): id is EditorCapabilityIdOf<K> =>
    EDITOR_CAPABILITIES[id].kind === kind

/** One option as the gateway's `/guide/intent` takes it; `isAction` is left out when false, the gateway's default. */
export type EditorCapabilityOption = { id: EditorCapabilityId; description: string; isAction?: true; teaches?: string; withMethod?: string }

export type DescribeIn = (language: 'en' | 'de', key: string) => string

/** Both languages, whatever the UI's: the request may be spoken in either. */
export function describeEditorCapabilities(translate: DescribeIn): EditorCapabilityOption[] {
    return EDITOR_CAPABILITY_IDS.map((id) => {
        const entry: CapabilityEntry = EDITOR_CAPABILITIES[id]
        const description = [...new Set([translate('en', entry.descriptionKey), translate('de', entry.descriptionKey)])].join(' · ')
        return {
            id,
            description,
            ...(entry.isAction ? { isAction: true as const } : {}),
            ...(entry.teaches ? { teaches: entry.teaches } : {}),
            ...(entry.withMethod ? { withMethod: entry.withMethod } : {}),
        }
    })
}
